    private static void smooth(java.awt.Graphics2D g2) {
        g2.setRenderingHint(java.awt.RenderingHints.KEY_ANTIALIASING, java.awt.RenderingHints.VALUE_ANTIALIAS_ON);
        g2.setRenderingHint(java.awt.RenderingHints.KEY_STROKE_CONTROL, java.awt.RenderingHints.VALUE_STROKE_PURE);
        g2.setRenderingHint(java.awt.RenderingHints.KEY_TEXT_ANTIALIASING, java.awt.RenderingHints.VALUE_TEXT_ANTIALIAS_ON);
    }

    /** Yellow rounded tile with the "H" mark. */
    private static class LogoTile extends javax.swing.JPanel {

        LogoTile() {
            setOpaque(false);
        }

        @Override
        protected void paintComponent(java.awt.Graphics g) {
            java.awt.Graphics2D g2 = (java.awt.Graphics2D) g.create();
            smooth(g2);
            int w = getWidth(), h = getHeight();
            g2.setColor(SUN);
            g2.fillRoundRect(0, 0, w, h, 24, 24);

            g2.setColor(INK);
            float dot = h * 0.135f;
            g2.fill(new java.awt.geom.Ellipse2D.Float((w - dot) / 2f, h * 0.23f - dot / 2f, dot, dot));

            int size = Math.round(h * 0.46f);
            g2.setFont(new java.awt.Font("Georgia", java.awt.Font.BOLD, size));
            java.awt.FontMetrics fm = g2.getFontMetrics();
            int x = (w - fm.stringWidth("H")) / 2;
            int y = Math.round(h * 0.63f + size * 0.35f);
            g2.drawString("H", x, y);
            g2.dispose();
        }
    }

