    /** Shared drawing for the two rounded input fields. */
    private static final class Field {

        static final int ARC = 20;

        static void background(java.awt.Graphics g, javax.swing.JComponent c) {
            java.awt.Graphics2D g2 = (java.awt.Graphics2D) g.create();
            smooth(g2);
            g2.setColor(java.awt.Color.WHITE);
            g2.fillRoundRect(0, 0, c.getWidth(), c.getHeight(), ARC, ARC);
            g2.dispose();
        }

        static void foreground(java.awt.Graphics g, javax.swing.text.JTextComponent c, String hint) {
            java.awt.Graphics2D g2 = (java.awt.Graphics2D) g.create();
            smooth(g2);
            if (c.getDocument().getLength() == 0) {
                g2.setFont(c.getFont());
                g2.setColor(HINT);
                java.awt.FontMetrics fm = g2.getFontMetrics();
                int y = (c.getHeight() - fm.getHeight()) / 2 + fm.getAscent();
                g2.drawString(hint, c.getInsets().left, y);
            }
            float sw = c.isFocusOwner() ? 2.5f : 1.5f;
            g2.setStroke(new java.awt.BasicStroke(sw));
            g2.setColor(INK);
            g2.draw(new java.awt.geom.RoundRectangle2D.Float(sw / 2f, sw / 2f, c.getWidth() - sw, c.getHeight() - sw, ARC, ARC));
            g2.dispose();
        }

        static void repaintOnFocus(javax.swing.JComponent c) {
            c.addFocusListener(new java.awt.event.FocusAdapter() {
                @Override
                public void focusGained(java.awt.event.FocusEvent e) {
                    c.repaint();
                }

                @Override
                public void focusLost(java.awt.event.FocusEvent e) {
                    c.repaint();
                }
            });
        }
    }

