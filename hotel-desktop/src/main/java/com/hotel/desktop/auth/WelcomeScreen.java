    @Override
    protected void paintComponent(Graphics graphics) {
        super.paintComponent(graphics);
        Graphics2D g = (Graphics2D) graphics.create();
        smooth(g);

        int width = getWidth();
        int height = getHeight();
        g.drawImage(backgroundImage, 0, 0, width, height, null);
        g.setPaint(new java.awt.LinearGradientPaint(
                0, 0, width, 0,
                new float[]{0f, 0.42f, 1f},
                new Color[]{
                    new Color(20, 18, 26, 245),
                    new Color(20, 18, 26, 225),
                    new Color(20, 18, 26, 46)
                }));
        g.fillRect(0, 0, width, height);

        g.setPaint(new GradientPaint(0, height * 0.72f, new Color(20, 18, 26, 0),
                0, height * 0.96f, new Color(20, 18, 26, 179)));
        g.fillRect(0, Math.round(height * 0.72f), width, Math.round(height * 0.24f));

        g.setColor(SUN);
        g.fillRect(0, 2, width, 45);
        g.fillRect(0, height - 45, width, 45);
        g.setColor(new Color(31, 27, 38));
        g.fillRect(0, 0, width, 35);
        g.fillRect(0, height - 35, width, 35);
        g.dispose();
    }

    private static BufferedImage loadBackgroundImage() {
        String resource = "/com/hotel/desktop/auth/welcome-background.png";
        try (InputStream stream = WelcomeScreen.class.getResourceAsStream(resource)) {
            if (stream == null) {
                throw new IllegalStateException("Missing welcome screen background resource: " + resource);
            }
            BufferedImage image = ImageIO.read(stream);
            if (image == null) {
                throw new IllegalStateException("Unsupported welcome screen background image: " + resource);
            }
            return image;
        } catch (IOException exception) {
            throw new UncheckedIOException("Unable to load welcome screen background: " + resource, exception);
        }
    }

    private static void smooth(Graphics2D graphics) {
        graphics.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
        graphics.setRenderingHint(RenderingHints.KEY_STROKE_CONTROL, RenderingHints.VALUE_STROKE_PURE);
        graphics.setRenderingHint(RenderingHints.KEY_TEXT_ANTIALIASING, RenderingHints.VALUE_TEXT_ANTIALIAS_ON);
    }

    private static final class LogoTile extends JPanel {

        private static final long serialVersionUID = 1L;

        LogoTile() {
            setOpaque(false);
        }

        @Override
        protected void paintComponent(Graphics graphics) {
            Graphics2D g = (Graphics2D) graphics.create();
            smooth(g);
            g.setColor(SUN);
            g.fill(new RoundRectangle2D.Double(0, 0, getWidth(), getHeight(), 12, 12));
            g.setColor(INK);
            g.fillOval(getWidth() / 2 - 4, 11, 8, 8);
            g.setFont(new Font("Georgia", Font.BOLD, 26));
            String mark = "H";
            g.drawString(mark, (getWidth() - g.getFontMetrics().stringWidth(mark)) / 2, 44);
            g.dispose();
        }
    }

    private static final class StartButton extends JButton {

        private static final long serialVersionUID = 1L;
        private boolean hovered;

        StartButton() {
            setFocusable(true);
            setOpaque(false);
            setContentAreaFilled(false);
            setBorderPainted(false);
            setBorder(null);
            setCursor(java.awt.Cursor.getPredefinedCursor(java.awt.Cursor.HAND_CURSOR));
            getAccessibleContext().setAccessibleDescription("Open the staff sign-in screen");
            addMouseListener(new MouseAdapter() {
                @Override
                public void mouseEntered(MouseEvent event) {
                    hovered = true;
                    repaint();
                }

                @Override
                public void mouseExited(MouseEvent event) {
                    hovered = false;
                    repaint();
                }
            });
        }

        @Override
        protected void paintComponent(Graphics graphics) {
            Graphics2D g = (Graphics2D) graphics.create();
            smooth(g);
            Color fill = getModel().isPressed()
                    ? new Color(230, 180, 0)
                    : hovered ? new Color(255, 218, 55) : SUN;
            g.setColor(fill);
            g.fillRoundRect(0, 0, getWidth(), getHeight(), 20, 20);
            g.dispose();
            super.paintComponent(graphics);

            g = (Graphics2D) graphics.create();
            smooth(g);
            g.setColor(INK);
            g.setStroke(new BasicStroke(2.4f, BasicStroke.CAP_ROUND, BasicStroke.JOIN_ROUND));
            int centerY = getHeight() / 2;
            int arrowTipX = getWidth() - Math.round(getWidth() * 0.258f);
            g.drawLine(arrowTipX - 22, centerY, arrowTipX, centerY);
            g.drawLine(arrowTipX - 8, centerY - 8, arrowTipX, centerY);
            g.drawLine(arrowTipX - 8, centerY + 8, arrowTipX, centerY);
            g.dispose();
        }
    }
